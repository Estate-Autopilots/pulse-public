#!/usr/bin/env node
// CLI: the pulse command's operation table comes from Pulse API v1's OpenAPI (services/api/openapi/v1.yaml), so every
// v1 operation is a command and a new one appears here when the reference is regenerated.
//   node scripts/generate.mjs           rewrite src/operations.generated.ts
//   node scripts/generate.mjs --check   fail when it is out of date (the package's lint step)
import { readFileSync, writeFileSync } from 'node:fs';

const SPEC = new URL('../../../services/api/openapi/v1.yaml', import.meta.url);
const OUT = new URL('../src/operations.generated.ts', import.meta.url);

/** v1.yaml is OpenAPI 3.1 written as JSON (which is YAML) after a comment header. */
export function readSpec(text = readFileSync(SPEC, 'utf8')) {
  return JSON.parse(text.split('\n').filter(line => !line.startsWith('#')).join('\n'));
}

export function operations(spec) {
  const deref = value => {
    if (!value || typeof value !== 'object' || typeof value.$ref !== 'string') return value;
    const parts = value.$ref.replace(/^#\//, '').split('/');
    return deref(parts.reduce((node, key) => node?.[key], spec));
  };
  const field = (name, where, required, raw) => {
    const s = deref(raw) ?? {};
    const types = [].concat(s.type ?? 'string');
    const type = types.find(t => t !== 'null') ?? 'string';
    const out = { name, in: where, required, type };
    if (types.includes('null')) out.nullable = true;
    if (Array.isArray(s.enum)) out.enum = s.enum.filter(v => v !== null).map(String);
    if (typeof s.pattern === 'string') out.pattern = s.pattern;
    if (type === 'array') {
      const items = deref(s.items) ?? {};
      if (typeof items.pattern === 'string') out.pattern = items.pattern;
      if (Array.isArray(items.enum)) out.enum = items.enum.map(String);
    }
    if (typeof s.minLength === 'number') out.minLength = s.minLength;
    if (typeof s.maxLength === 'number') out.maxLength = s.maxLength;
    if (typeof s.description === 'string') out.description = s.description.replace(/\s+/g, ' ').trim();
    return out;
  };
  const out = [];
  for (const [path, item] of Object.entries(spec.paths ?? {})) {
    for (const [method, op] of Object.entries(item)) {
      if (!['get', 'post', 'put', 'patch', 'delete'].includes(method) || !op.operationId) continue;
      // Only operations a person's sign-in or a bearer key can call; the install-local service paths need a psvc_
      // service key and stay reachable through `pulse api`.
      const security = (op.security ?? spec.security ?? []).find(s => s.bearer);
      if (!security) continue;
      const params = [...(item.parameters ?? []), ...(op.parameters ?? [])].map(deref);
      const fields = params.filter(p => p.in === 'path' || p.in === 'query').map(p => field(p.name, p.in, p.in === 'path' || !!p.required, p.schema));
      const body = deref(deref(op.requestBody)?.content?.['application/json']?.schema);
      for (const [name, schema] of Object.entries(body?.properties ?? {})) fields.push(field(name, 'body', (body.required ?? []).includes(name), schema));
      out.push({
        operationId: op.operationId, method: method.toUpperCase(), path, summary: String(op.summary ?? '').replace(/\s+/g, ' ').trim(),
        scopes: security.bearer, write: method !== 'get', hasBody: !!body,
        idempotencyKey: params.some(p => p.in === 'header' && String(p.name).toLowerCase() === 'idempotency-key'),
        fields,
      });
    }
  }
  return out;
}

export function render(spec) {
  return `// Generated by scripts/generate.mjs from services/api/openapi/v1.yaml (API ${spec.info?.version ?? '?'}). Do not edit:
// run \`pnpm --filter @pulse/cli generate\` after the v1 reference changes; \`pnpm --filter @pulse/cli lint\` checks it.
export type FieldType = 'string' | 'boolean' | 'array' | 'number' | 'integer' | 'object';
export type Field = { name: string; in: 'path' | 'query' | 'body'; required: boolean; type: FieldType; nullable?: boolean; enum?: string[];
  pattern?: string; minLength?: number; maxLength?: number; description?: string };
export type Operation = { operationId: string; method: 'GET' | 'POST' | 'PUT' | 'PATCH' | 'DELETE'; path: string; summary: string;
  scopes: string[]; write: boolean; hasBody: boolean; idempotencyKey: boolean; fields: Field[] };

export const API_VERSION = ${JSON.stringify(spec.info?.version ?? '')};
export const OPERATIONS: readonly Operation[] = ${JSON.stringify(operations(spec), null, 2)};
`;
}

if (import.meta.url === `file://${process.argv[1]}` || process.argv[1]?.endsWith('generate.mjs')) {
  const text = render(readSpec());
  if (process.argv.includes('--check')) {
    let current = '';
    try { current = readFileSync(OUT, 'utf8'); } catch { /* missing counts as stale */ }
    if (current !== text) {
      console.error('src/operations.generated.ts is out of date with services/api/openapi/v1.yaml; run: pnpm --filter @pulse/cli generate');
      process.exit(1);
    }
    console.log(`operations.generated.ts is current (${operations(readSpec()).length} operations)`);
  } else {
    writeFileSync(OUT, text);
    console.log(`wrote src/operations.generated.ts (${operations(readSpec()).length} operations)`);
  }
}

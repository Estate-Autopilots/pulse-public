"""pulse-codegen: TypeScript types and Pydantic models from packages/schemas (envelope + registry).

    pulse-codegen            # write the two generated files
    pulse-codegen --check    # exit 1 when a generated file is stale (tools/ci.sh runs this)

Inputs: packages/schemas/envelope.schema.json (appendix B) and packages/schemas/registry.yaml (appendix D).
Outputs (committed; regenerate in the same change that edits an input):
  packages/schemas/generated/events.ts             for the web app, the API and the desktop UI
  packages/sdk-py/src/pulse_sdk/generated/events.py Pydantic v2 models for the Python services
Every data model forbids undeclared fields, like the validator and the database trigger. Field types come from the
registry's `fields`; the four types with full data schemas in the envelope (agent.usage.hourly,
agent.cid_time.hourly, app.work.delta, agent.commands.hourly) use those exact schemas. No third-party
generator: the output is a pure function of the inputs, so the freshness check is exact.
"""

from __future__ import annotations

import argparse
import json
import keyword
import re
import sys
from pathlib import Path

from . import registry as reg
from .paths import repo_root, schemas_dir

HEADER = "GENERATED by pulse-codegen from packages/schemas/{envelope.schema.json,registry.yaml}. Do not edit."
ENVELOPE_ORDER = ("specversion", "id", "source", "type", "time", "subject", "orgid", "purpose", "sensitivity",
                  "visibility", "data")


def outputs(root: Path | None = None) -> tuple[Path, Path]:
    root = root or repo_root()
    return (root / "packages" / "schemas" / "generated" / "events.ts",
            root / "packages" / "sdk-py" / "src" / "pulse_sdk" / "generated" / "events.py")


def class_name(event_type: str) -> str:
    return "".join(part.capitalize() for part in re.split(r"[._]", event_type)) + "Data"


def data_schemas(envelope: dict) -> dict[str, dict]:
    """Full data schemas declared in the envelope's allOf conditions, by event type."""
    out = {}
    for cond in envelope.get("allOf", []):
        t = cond.get("if", {}).get("properties", {}).get("type", {}).get("const")
        data = cond.get("then", {}).get("properties", {}).get("data")
        if t and data:
            out[t] = data
    return out


# ---------------------------------------------------------------------------------------------------- TypeScript
def ts_type(schema: dict, indent: str = "  ") -> str:
    if "anyOf" in schema:
        return " | ".join(ts_type(s, indent) for s in schema["anyOf"])
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    t = schema.get("type")
    if t in ("integer", "number"):
        return "number"
    if t == "string":
        return "string"
    if t == "boolean":
        return "boolean"
    if t == "array":
        return f"Array<{ts_type(schema.get('items', {}), indent)}>"
    if t == "object":
        props = schema.get("properties")
        if props:
            req = set(schema.get("required", []))
            inner = indent + "  "
            lines = [f"{inner}{k}{'' if k in req else '?'}: {ts_type(v, inner)};" for k, v in props.items()]
            return "{\n" + "\n".join(lines) + f"\n{indent}}}"
        extra = schema.get("additionalProperties")
        if isinstance(extra, dict):
            return f"{{ [key: string]: {ts_type(extra, indent)} }}"
        return "{ [key: string]: JsonValue }"
    return "JsonValue"


def render_ts(registry: reg.Registry, envelope: dict) -> str:
    full = data_schemas(envelope)
    types = sorted(registry.types)
    retention = sorted({et.retention for et in registry.types.values()})
    props = envelope["properties"]
    out = [f"// {HEADER}", "/* eslint-disable */", ""]
    out.append("export type JsonValue = string | number | boolean | null | JsonValue[] | { [key: string]: JsonValue };")
    out.append(f"export type Purpose = {' | '.join(json.dumps(p) for p in reg.CANONICAL_PURPOSES)};")
    out.append(f"export type Visibility = {ts_type(props['visibility'])};")
    out.append(f"export type Sensitivity = {ts_type(props['sensitivity'])};")
    out.append(f"export type ActorKind = {ts_type(props['actorkind'])};")
    out.append(f"export type RetentionClass = {' | '.join(json.dumps(r) for r in retention)};")
    out.append("export type EventType =")
    out += [f"  | {json.dumps(t)}" for t in types]
    out[-1] += ";"
    out += ["", f"export const REGISTRY_VERSION = {registry.version};", "",
            "export interface EventTypeSpec {",
            "  purposes: readonly Purpose[];",
            "  sensitivity: Sensitivity;   // floor",
            "  visibility: Visibility;     // floor: an event may be stricter, never looser",
            "  retention: RetentionClass;",
            "  emitters: readonly string[];",
            "  subject: string;",
            "  required: readonly string[];",
            "  optional: readonly string[];",
            "}", "",
            "export const REGISTRY: { readonly [T in EventType]: EventTypeSpec } = {"]
    for t in types:
        et = registry.types[t]
        spec = {"purposes": list(et.purposes), "sensitivity": et.sensitivity, "visibility": et.visibility,
                "retention": et.retention, "emitters": list(et.emitters), "subject": et.subject,
                "required": list(et.data_required), "optional": list(et.data_optional)}
        out.append(f"  {json.dumps(t)}: {json.dumps(spec)},")
    out += ["};", ""]
    for t in types:
        et = registry.types[t]
        schema = full.get(t, et.data_schema)
        if schema.get("properties"):
            out.append(f"export type {class_name(t)} = {ts_type(schema, '')};")
        else:
            out.append(f"export type {class_name(t)} = Record<string, never>;")
    out += ["", "export interface EventData {"]
    out += [f"  {json.dumps(t)}: {class_name(t)};" for t in types]
    out += ["}", "", "/** CloudEvents 1.0 structured envelope with the Pulse extensions (appendix B). */",
            "export interface Envelope<T extends EventType = EventType> {"]
    req = set(envelope.get("required", []))
    for k in list(ENVELOPE_ORDER) + sorted(set(props) - set(ENVELOPE_ORDER)):
        if k == "type":
            out.append("  type: T;")
        elif k == "data":
            out.append("  data: EventData[T];")
        else:
            out.append(f"  {k}{'' if k in req else '?'}: {ts_type(props[k])};")
    out += ["}", ""]
    return "\n".join(out)


# ------------------------------------------------------------------------------------------------------ Pydantic
def py_type(schema: dict, name_hint: str, extra_classes: list[str]) -> str:
    """Annotation for a JSON Schema fragment; nested objects become classes appended to extra_classes."""
    if "anyOf" in schema:
        return " | ".join(py_type(s, f"{name_hint}{i}", extra_classes) for i, s in enumerate(schema["anyOf"]))
    if "const" in schema:
        return f"Literal[{schema['const']!r}]"
    if "enum" in schema:
        return f"Literal[{', '.join(repr(v) for v in schema['enum'])}]"
    t = schema.get("type")
    cons = []
    for key, arg in (("minimum", "ge"), ("maximum", "le")):
        if key in schema:
            cons.append(f"{arg}={schema[key]!r}")
    if "pattern" in schema:
        cons.append(f"pattern={schema['pattern']!r}")
    for key, arg in (("minLength", "min_length"), ("maxLength", "max_length")):
        if key in schema:
            cons.append(f"{arg}={schema[key]!r}")
    if t == "integer":
        base = "int"
    elif t == "number":
        base = "float"
    elif t == "boolean":
        base = "bool"
    elif t == "string":
        base = {"date-time": "datetime", "date": "date", "uuid": "UUID"}.get(schema.get("format"), "str")
        if base != "str":
            cons = []
    elif t == "array":
        item = py_type(schema.get("items", {}), name_hint + "Item", extra_classes)
        if "maxItems" in schema:
            return f"Annotated[list[{item}], Field(max_length={schema['maxItems']})]"
        return f"list[{item}]"
    elif t == "object":
        props = schema.get("properties")
        if props:
            extra_classes.append(py_class(name_hint, schema, extra_classes))
            return name_hint
        extra = schema.get("additionalProperties")
        value = py_type(extra, name_hint + "Value", extra_classes) if isinstance(extra, dict) else "Any"
        return f"dict[str, {value}]"
    else:
        return "Any"
    return f"Annotated[{base}, Field({', '.join(cons)})]" if cons else base


def py_class(name: str, schema: dict, extra_classes: list[str]) -> str:
    req = set(schema.get("required", []))
    lines = [f"class {name}(_Strict):"]
    if schema.get("description"):
        lines.append(f"    \"\"\"{schema['description']}\"\"\"")
    body = []
    for k, v in schema.get("properties", {}).items():
        ann = py_type(v, name.removesuffix("Data") + _camel(k), extra_classes)
        body.append(py_field(k, ann, k in req))
    return "\n".join(lines + (body or ["    pass"]))


def py_field(name: str, ann: str, required: bool) -> str:
    """A model field; Python keywords (e.g. leave.declared's `from`) get a trailing underscore and an alias."""
    if keyword.iskeyword(name) or not name.isidentifier():
        attr = re.sub(r"\W", "_", name) + "_"
        default = "..." if required else "None"
        opt = "" if required else " | None"
        return f"    {attr}: {ann}{opt} = Field({default}, alias={name!r})"
    return f"    {name}: {ann}" if required else f"    {name}: {ann} | None = None"


def _camel(s: str) -> str:
    return "".join(p.capitalize() for p in s.split("_"))


def render_py(registry: reg.Registry, envelope: dict) -> str:
    full = data_schemas(envelope)
    types = sorted(registry.types)
    props = envelope["properties"]
    classes: list[str] = []
    for t in types:
        classes.append(py_class(class_name(t), full.get(t, registry.types[t].data_schema), classes))
    env_lines = []
    req = set(envelope.get("required", []))
    for k in list(ENVELOPE_ORDER) + sorted(set(props) - set(ENVELOPE_ORDER)):
        if k == "type":
            ann = "EventType"
        elif k == "data":
            ann = "dict[str, Any]"
        else:
            ann = py_type(props[k], "Envelope" + _camel(k), classes)
        env_lines.append(py_field(k, ann, k in req))
    out = [f"# {HEADER}", "# ruff: noqa: E501",
           '"""Pydantic v2 models for Pulse events (spec appendix B and D)."""', "",
           "from __future__ import annotations", "", "from datetime import date, datetime",
           "from typing import Annotated, Any, Literal", "from uuid import UUID", "",
           "from pydantic import BaseModel, ConfigDict, Field", "",
           f"REGISTRY_VERSION = {registry.version}",
           f"Purpose = Literal[{', '.join(repr(p) for p in reg.CANONICAL_PURPOSES)}]",
           "EventType = Literal[", *[f"    {t!r}," for t in types], "]", "", "",
           "class _Strict(BaseModel):",
           "    \"\"\"Undeclared fields are rejected (ADR-0025), as by the validator and the database trigger.\"\"\"",
           "    model_config = ConfigDict(extra=\"forbid\", populate_by_name=True)", "", ""]
    out.append("\n\n\n".join(classes))
    out += ["", "", "DATA_MODELS: dict[str, type[_Strict]] = {"]
    out += [f"    {t!r}: {class_name(t)}," for t in types]
    out += ["}", "", "",
            "class Envelope(_Strict):",
            "    \"\"\"CloudEvents 1.0 structured envelope with the Pulse extensions.\"\"\"",
            *env_lines, "",
            "    def typed_data(self) -> _Strict:",
            "        \"\"\"The data as its registered model (raises pydantic.ValidationError).\"\"\"",
            "        return DATA_MODELS[self.type].model_validate(self.data)", ""]
    return "\n".join(out)


def generate(root: Path | None = None) -> dict[Path, str]:
    registry = reg.load(schemas_dir() / "registry.yaml")
    envelope = json.loads((schemas_dir() / "envelope.schema.json").read_text(encoding="utf-8"))
    ts_path, py_path = outputs(root)
    return {ts_path: render_ts(registry, envelope), py_path: render_py(registry, envelope)}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="pulse-codegen", description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="fail when a generated file is stale")
    args = ap.parse_args(argv)
    stale = []
    for path, text in generate().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        if args.check:
            stale.append(str(path.relative_to(repo_root())))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(repo_root())}")
    if stale:
        print("stale generated code (run `uv run pulse-codegen` and commit): " + ", ".join(stale), file=sys.stderr)
        return 1
    if args.check:
        print("generated code is fresh")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
